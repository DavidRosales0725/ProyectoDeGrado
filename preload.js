const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  listarProductos: () => ipcRenderer.invoke('productos:listar'),
  buscarProductoPorCodigo: (codigo) => ipcRenderer.invoke('productos:buscarPorCodigo', codigo),
  crearProducto: (p) => ipcRenderer.invoke('productos:crear', p),
  actualizarProducto: (id, p) => ipcRenderer.invoke('productos:actualizar', id, p),
  eliminarProducto: (id) => ipcRenderer.invoke('productos:eliminar', id),
  contarStockBajo: () => ipcRenderer.invoke('productos:stockBajo'),
  ajustarStock: (d) => ipcRenderer.invoke('inventario:ajustar', d),
  registrarVenta: (datos) => ipcRenderer.invoke('ventas:registrar', datos),
  anularVenta: (datos) => ipcRenderer.invoke('ventas:anular', datos),
  corregirVenta: (datos) => ipcRenderer.invoke('ventas:corregir', datos),
  listarVentas: () => ipcRenderer.invoke('ventas:listar'),
  obtenerResumen: () => ipcRenderer.invoke('dashboard:resumen'),
  obtenerReportePorDia: (rango) => ipcRenderer.invoke('reportes:porDia', rango),
  obtenerVentasDelDia: (fecha) => ipcRenderer.invoke('reportes:ventasDelDia', fecha),
  hayUsuarios: () => ipcRenderer.invoke('auth:hayUsuarios'),
  crearPrimerAdmin: (datos) => ipcRenderer.invoke('auth:crearPrimerAdmin', datos),
  iniciarSesion: (datos) => ipcRenderer.invoke('auth:login', datos),
  cerrarSesion: () => ipcRenderer.invoke('auth:logout'),
  obtenerSesion: () => ipcRenderer.invoke('auth:actual'),
  cambiarMiClave: (datos) => ipcRenderer.invoke('auth:cambiarMiClave', datos),
  listarUsuarios: () => ipcRenderer.invoke('usuarios:listar'),
  crearUsuario: (datos) => ipcRenderer.invoke('usuarios:crear', datos),
  cambiarRolUsuario: (id, rol) => ipcRenderer.invoke('usuarios:cambiarRol', id, rol),
  activarUsuario: (id) => ipcRenderer.invoke('usuarios:activar', id),
  desactivarUsuario: (id) => ipcRenderer.invoke('usuarios:desactivar', id),
  restablecerClaveUsuario: (id, password) => ipcRenderer.invoke('usuarios:restablecerClave', id, password),
  consultarKardex: (filtros) => ipcRenderer.invoke('kardex:consultar', filtros),
  seleccionarImagenProducto: () => ipcRenderer.invoke('imagenes:seleccionar'),
});
